type LebanonFoodInput = {
  id: string;
  name: string;
  serving: string;
  energyKcal: number;
  proteinG: number;
  carbohydrateG: number;
  fatG: number;
  sugarG?: number;
  sodiumMg?: number;
  ironMg?: number;
};

function record(category: "Traditional dish" | "Arabic sweet", row: LebanonFoodInput): FoodDatasetRecord {
  const extras: Record<string, number> = {};
  if (row.ironMg !== undefined) extras.ironMg = row.ironMg;
  return {
    sourceFoodId: `lb-2021-${row.id}`,
    name: row.name,
    category,
    servingDescription: row.serving,
    referenceQuantity: 100,
    referenceUnit: "g",
    energyKcal: row.energyKcal,
    proteinG: row.proteinG,
    carbohydrateG: row.carbohydrateG,
    fatG: row.fatG,
    sugarG: row.sugarG ?? null,
    sodiumMg: row.sodiumMg ?? null,
    extraNutrients: Object.keys(extras).length > 0 ? extras : undefined,
  };
}

